const DICTS: Record<Locale, Dict> = { en, ar };

export type Translator = (key: keyof typeof en) => string;

export function getTranslator(locale: string): Translator {
  const dict = DICTS[(locale as Locale) in DICTS ? (locale as Locale) : "en"];
  return (key) => dict[key] ?? en[key] ?? String(key);
}

